--:4.- REALIZAR UNA FUNCION QUE CALCULE EL AREA DEL TRIANGULO, QUE RECIBA COMO PARAMETROS LA BASE Y ALTURA
CREATE OR REPLACE FUNCTION AREA_TRIANGULO(BASE NUMBER, ALTURA NUMBER)
RETURN NUMBER
IS
BEGIN
    RETURN (BASE * ALTURA) / 2;
END;
/
