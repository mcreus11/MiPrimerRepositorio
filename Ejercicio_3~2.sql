--:8.- REALIZAR UNA FUNCION QUE RECIBA UN NUMERO Y DEVUELVA UN MNESAJE INDICANDO SI ES MULTIPLO DE 3 O NO
CREATE OR REPLACE FUNCTION MULTIPLO_TRES(NUMERO NUMBER)
RETURN VARCHAR2
IS
BEGIN
    IF MOD(NUMERO, 3) = 0 THEN
        RETURN 'ES MULTIPLO DE 3';
    ELSE
        RETURN 'NO ES MULTIPLO DE 3';
    END IF;
END;
/
SELECT MULTIPLO_TRES(10) FROM DUAL;


