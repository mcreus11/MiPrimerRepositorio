--5.- REALIZAR UNA FUNCION QUE RECIBA UN NUMERO DEL 1 AL 7 Y DEVULVA EL NOMBRE DEL DIA DE LA SEMANA
CREATE OR REPLACE FUNCTION DIA_SEMANA(numero NUMBER)
RETURN VARCHAR2
IS
    NOMBRE_DIA VARCHAR2(20);
BEGIN
    CASE NUMERO
        WHEN 1 THEN NOMBRE_DIA := 'LUNES';
        WHEN 2 THEN NOMBRE_DIA := 'MARTES';
        WHEN 3 THEN NOMBRE_DIA := 'MIERCOLES';
        WHEN 4 THEN NOMBRE_DIA := 'JUEVES';
        WHEN 5 THEN NOMBRE_DIA := 'VIERNES';
        WHEN 6 THEN NOMBRE_DIA := 'SABADO';
        WHEN 7 THEN NOMBRE_DIA := 'DOMINGO';
        ELSE
            NOMBRE_DIA := 'DIA INVALIDO';
    END CASE;

    RETURN NOMBRE_DIA;
END;
/

SELECT DIA_SEMANA(5) FROM DUAL;


--6.- REALIZAR UNA FUNCION QUE RECIBA UNA EDAD Y DEVUELVA UN MENSAJE INDICANDO SI ES MAYOR O MENOR DE EDAD
CREATE OR REPLACE FUNCTION VERIFICAR_EDAD(EDAD NUMBER)
RETURN VARCHAR2
IS
BEGIN
    IF EDAD >= 18 THEN
        RETURN 'ES MAYOR DE EDAD';
    ELSE
        RETURN 'ES MENOR DE EDAD';
    END IF;
END;
/

SELECT VERIFICAR_EDAD(17) FROM DUAL;

