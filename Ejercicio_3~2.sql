--•1.- REALIZAR UNA FUNCION QUE CALCULE EL AREA DEL CIRCULO Y QUE RECIBA COMO PARAMETRO EL RADIO
CREATE OR REPLACE FUNCTION AREA_CIRCULO(RADIO NUMBER)
RETURN NUMBER
IS
    AREA NUMBER;
BEGIN
    AREA := 3.1416 * RADIO * RADIO;
    RETURN AREA;
END;
/

SELECT AREA_CIRCULO(5) FROM DUAL;

--2•- USAR UNA FUNCION QUE RECIBA UN NUMERO DEL 1 AL 12 Y DEVUELVA EL NOMBRE DEL MES CORRESPONDIENIE
CREATE OR REPLACE FUNCTION NOMBRE_MES(NUMERO NUMBER)
RETURN VARCHAR2
IS
    MES_NOMBRE VARCHAR2(20);
BEGIN
    MES_NOMBRE := TO_CHAR(TO_DATE(NUMERO, 'MM'), 'Month');
    RETURN (MES_NOMBRE);
END;
/
SELECT NOMBRE_MES(3) FROM DUAL;


