--4. Consultas con CASE
--Mostrar el salario de los empleados junto con una etiqueta que indique si el salario es "Alto" (> 5000), "Medio" (2000-5000) o "Bajo" (< 2000).
SELECT 
    NOMBRE AS EMPLEADO,
    SALARIO,
    CASE 
        WHEN SALARIO > 5000 THEN 'ALTO'
        WHEN SALARIO BETWEEN 2000 AND 5000 THEN 'MEDIO'
        WHEN SALARIO < 2000 THEN 'BAJO'
        ELSE 'SALARIO NO DEFINIDO'
    END AS CLASIFICACION_SALARIO
FROM EMPLEADO;
    
--Mostrar el nombre del proyecto y la duración del proyecto, junto con una etiqueta que indique si el proyecto está "Activo" 
--(si la fecha actual está dentro del rango) o "Inactivo".

SELECT 
    NOMBRE AS PROYECTO,
    FECHA_INICIO,
    FECHA_FIN,
    (FECHA_FIN - FECHA_INICIO) AS DURACION_EN_DIAS,
    CASE 
        WHEN SYSDATE BETWEEN FECHA_INICIO AND FECHA_FIN THEN 'ACTIVO'
        ELSE 'INACTIVO'
    END AS ESTADO_PROYECTO
FROM PROYECTO;

