/*Actividad 6: Cursor FOR y manejo de excepciones
Crea un procedimiento que:
Use un cursor FOR para recorrer todos los proyectos.
Imprima su nombre y duración.
Si la duración es negativa (fecha_fin < fecha_inicio), lance una excepción y registre un mensaje: 'Error en proyecto: [NOMBRE]'.

*/
CREATE OR REPLACE PROCEDURE PR_REPORTE_PROYECTOS IS

  EXCEPTION_PROYECTO_ERR EXCEPTION;
  ERROR_MSG VARCHAR2(100);

BEGIN
  FOR REC IN (SELECT ID_PROYECTO, NOMBRE, FECHA_INICIO, FECHA_FIN FROM PROYECTO) LOOP
    DECLARE
      DURACION NUMBER;
    BEGIN
      DURACION := REC.FECHA_FIN - REC.FECHA_INICIO;

      IF DURACION < 0 THEN
        ERROR_MSG := 'ERROR EN EL PROYECTO: ' || REC.NOMBRE;
        RAISE EXCEPTION_PROYECTO_ERR;
      END IF;

      DBMS_OUTPUT.PUT_LINE('PROYECTO: ' || REC.NOMBRE || ' , DURACION: ' || DURACION || ' DIAS.');

    EXCEPTION
      WHEN EXCEPTION_PROYECTO_ERR THEN
        DBMS_OUTPUT.PUT_LINE(ERROR_MSG);
    END;
  END LOOP;
END;
/
BEGIN
  PR_REPORTE_PROYECTOS;
END;
/

