/*Actividad 3: Procedimiento con cursor y condiciones
Crea un procedimiento que:
Recorra todos los empleados de un departamento dado (usando cursor).
Imprima sus nombres y, si tienen más de 100 horas trabajadas en total, que también imprima: "Empleado con alta carga de trabajo"

*/

CREATE OR REPLACE PROCEDURE PR_CARGA_TRABAJO_DEPTO (
    P_ID_DEPARTAMENTO IN NUMBER
)
IS
    CURSOR C_EMPLEADOS IS
        SELECT E.ID_EMPLEADO, E.NOMBRE,
               NVL(SUM(A.HORAS_TRABAJADAS), 0) AS TOTAL_HORAS
        FROM EMPLEADO E
        LEFT JOIN ASIGNACION A ON E.ID_EMPLEADO = A.EMPLEADO_ID
        WHERE E.DEPARTAMENTO_ID = P_ID_DEPARTAMENTO
        GROUP BY E.ID_EMPLEADO, E.NOMBRE;

    V_ID_EMPLEADO   EMPLEADO.ID_EMPLEADO%TYPE;
    V_NOMBRE        EMPLEADO.NOMBRE%TYPE;
    V_TOTAL_HORAS   NUMBER;
BEGIN
    OPEN C_EMPLEADOS;
    LOOP
        FETCH C_EMPLEADOS INTO V_ID_EMPLEADO, V_NOMBRE, V_TOTAL_HORAS;
        EXIT WHEN C_EMPLEADOS%NOTFOUND;

        DBMS_OUTPUT.PUT_LINE('EMPLEADO: ' || V_NOMBRE || ' , TOTAL: ' || V_TOTAL_HORAS);

        IF V_TOTAL_HORAS > 100 THEN
            DBMS_OUTPUT.PUT_LINE(' EMPLEADO CON ALTA CARGA DE TRABAJO');
        END IF;
    END LOOP;
    CLOSE C_EMPLEADOS;
END;
/

BEGIN
    PR_CARGA_TRABAJO_DEPTO(1);
END;

/*Actividad 4: Paquete EMPLEADO_UTILS
Declara un paquete con:
