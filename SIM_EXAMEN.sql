/*Actividad 2: Función que clasifica un proyecto
Crea una función que reciba un ID_PROYECTO y devuelva un mensaje como:
'Corto' si dura menos de 30 días.
'Mediano' entre 30 y 90 días.
'Largo' si dura más de 90 días.

*/
CREATE OR REPLACE FUNCTION FN_CLASIFICAR_PROYECTO (P_ID_PROYECTO NUMBER)
RETURN VARCHAR2
IS
    V_DURACION NUMBER;
BEGIN
    SELECT FECHA_FIN - FECHA_INICIO
    INTO V_DURACION
    FROM PROYECTO
    WHERE ID_PROYECTO = P_ID_PROYECTO;

    IF V_DURACION < 30 THEN
        RETURN 'CORTO';
    ELSIF V_DURACION BETWEEN 30 AND 90 THEN
        RETURN 'MEDIANO';
    ELSE
        RETURN 'LARGO';
    END IF;
END;
