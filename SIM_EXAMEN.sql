Tome como parámetro el ID_DEPARTAMENTO.
Imprima los nombres y salarios de todos los empleados en ese departamento.
Si el departamento no tiene empleados, imprima un mensaje indicando que no hay empleados en ese departamento.
*/
CREATE OR REPLACE PROCEDURE PR_EMPLEADOS_X_DEPARTAMENTO(P_ID_DEP IN NUMBER)
IS
    V_CONTADOR NUMBER := 0;
BEGIN
    SELECT COUNT(*) INTO V_CONTADOR
    FROM EMPLEADO
    WHERE DEPARTAMENTO_ID = P_ID_DEP;

    IF V_CONTADOR = 0 THEN
        DBMS_OUTPUT.PUT_LINE('NO HAY EMPLEADOS EN ESE DEPARTAMENTO.');
    ELSE
        FOR EMP IN (
            SELECT NOMBRE, SALARIO
            FROM EMPLEADO
            WHERE DEPARTAMENTO_ID = P_ID_DEP
        )
        LOOP
            DBMS_OUTPUT.PUT_LINE('EMPLEADO: ' || EMP.NOMBRE || ' , SALARIO: ' || EMP.SALARIO);
        END LOOP;
    END IF;
END;

