CREATE OR REPLACE PACKAGE BODY PKG_PROYECTOS IS

  FUNCTION FN_HORAS_EMPLEADO_PROYECTO(
    P_EMPLEADO_ID IN NUMBER,
    P_PROYECTO_ID IN NUMBER
  ) RETURN NUMBER IS
    V_TOTAL_HORAS NUMBER := 0;
  BEGIN
    SELECT NVL(SUM(HORAS_TRABAJADAS), 0)
      INTO V_TOTAL_HORAS
      FROM ASIGNACION
      WHERE EMPLEADO_ID = P_EMPLEADO_ID
        AND PROYECTO_ID = P_PROYECTO_ID;

    RETURN V_TOTAL_HORAS;
  END FN_HORAS_EMPLEADO_PROYECTO;

  PROCEDURE PR_REPORTE_HORAS_EMPLEADO(
    P_EMPLEADO_ID IN NUMBER
  ) IS
  BEGIN
    FOR REC IN (
      SELECT P.ID_PROYECTO, P.NOMBRE
      FROM PROYECTO P
      INNER JOIN ASIGNACION A ON P.ID_PROYECTO = A.PROYECTO_ID
      WHERE A.EMPLEADO_ID = P_EMPLEADO_ID
    ) LOOP
      DBMS_OUTPUT.PUT_LINE(
        'PROYECTO: ' || REC.NOMBRE || ' , HORAS TRABAJADAS: ' || FN_HORAS_EMPLEADO_PROYECTO(P_EMPLEADO_ID, REC.ID_PROYECTO)
      );
    END LOOP;
  END PR_REPORTE_HORAS_EMPLEADO;

END PKG_PROYECTOS;
