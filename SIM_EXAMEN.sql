CREATE OR REPLACE PACKAGE EMPLEADO_UTILS AS
    FUNCTION FN_CLASIFICAR_SALARIO(P_SALARIO NUMBER) RETURN VARCHAR2;

    PROCEDURE PR_REPORTE_EMPLEADOS;

    CURSOR C_EMPLEADOS IS
        SELECT ID_EMPLEADO, NOMBRE, SALARIO FROM EMPLEADO;
END EMPLEADO_UTILS;
/

CREATE OR REPLACE PACKAGE BODY EMPLEADO_UTILS AS

    FUNCTION FN_CLASIFICAR_SALARIO(P_SALARIO NUMBER) RETURN VARCHAR2 IS
    BEGIN
        IF P_SALARIO > 5000 THEN
            RETURN 'ALTO';
        ELSIF P_SALARIO BETWEEN 2000 AND 5000 THEN
            RETURN 'MEDIO';
        ELSE
            RETURN 'BAJO';
        END IF;
    END FN_CLASIFICAR_SALARIO;

    PROCEDURE PR_REPORTE_EMPLEADOS IS
        V_ID_EMPLEADO EMPLEADO.ID_EMPLEADO%TYPE;
        V_NOMBRE      EMPLEADO.NOMBRE%TYPE;
        V_SALARIO     EMPLEADO.SALARIO%TYPE;
        V_CLASIFICACION VARCHAR2(10);
    BEGIN
        OPEN C_EMPLEADOS;
        LOOP
            FETCH C_EMPLEADOS INTO V_ID_EMPLEADO, V_NOMBRE, V_SALARIO;
            EXIT WHEN C_EMPLEADOS%NOTFOUND;

            V_CLASIFICACION := FN_CLASIFICAR_SALARIO(V_SALARIO);

            DBMS_OUTPUT.PUT_LINE('ID: ' || V_ID_EMPLEADO || ', NOMBRE: ' || V_NOMBRE || 
                                 ', SALARIO: ' || V_SALARIO || ' -> ' || V_CLASIFICACION);
        END LOOP;
        CLOSE C_EMPLEADOS;
    END PR_REPORTE_EMPLEADOS;

END EMPLEADO_UTILS;
/
BEGIN
    EMPLEADO_UTILS.PR_REPORTE_EMPLEADOS;
