--;1.- REALIZAR UN CURSOR QUE MUESTRE EL TITULO Y PRECIO DE TODOS LOS LIBROS

DECLARE CURSOR TITULO_PRECIOS IS
    SELECT TITULO, PRECIO FROM LIBRO;
    
    LV_TITULO LIBRO.TITULO%TYPE;
    LV_PRECIO LIBRO.PRECIO%TYPE;
BEGIN
    OPEN TITULO_PRECIOS;
    LOOP
        FETCH TITULO_PRECIOS INTO LV_TITULO, LV_PRECIO;
        EXIT WHEN TITULO_PRECIOS%NOTFOUND;
        DBMS_OUTPUT.PUT_LINE('TITULO: ' || LV_TITULO || ' , PRECIO: ' || LV_PRECIO);
    END LOOP;
    CLOSE TITULO_PRECIOS;
END;
/


--2.- REALIZAR UN CURSOR QUE MUESTRE SOLO LOS LIBROS CON PRECIO MAYOR A 300 ORDENADOS POR PRECIOS DESCENDENIE
DECLARE CURSOR LIBROS_CAROS 
IS
        SELECT TITULO, PRECIO 
        FROM LIBRO 
        WHERE PRECIO > 300
        ORDER BY PRECIO DESC;
    
    LV_TITULO LIBRO.TITULO%TYPE;
    LV_PRECIO LIBRO.PRECIO%TYPE;
BEGIN
    OPEN LIBROS_CAROS;
    LOOP
        FETCH LIBROS_CAROS INTO LV_TITULO, LV_PRECIO;
        EXIT WHEN LIBROS_CAROS%NOTFOUND;
        DBMS_OUTPUT.PUT_LINE('LIBRO: ' || LV_TITULO || ' , PRECIO: ' || LV_PRECIO);
    END LOOP;
    CLOSE LIBROS_CAROS;
END;
